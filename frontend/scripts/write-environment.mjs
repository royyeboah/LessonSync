import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const apiUrl = (process.env.API_URL ?? '').replace(/\/$/, '');

const content = `// Generated by scripts/write-environment.mjs before production builds.
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)}
};
`;

writeFileSync(join(__dirname, '../src/environments/environment.prod.ts'), content);
console.log(`Wrote environment.prod.ts (apiUrl: ${apiUrl || '(not set)'})`);
